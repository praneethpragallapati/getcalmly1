// Regenerate prisma/sync_schema.sql from prisma/schema.prisma.
//
//   npm run db:sync-sql
//
// The sync script is the one-paste fix for a database that has fallen behind
// the app (Supabase → SQL Editor → paste → Run). It went stale because it was
// generated once by hand and never again, so newer tables and columns were
// missing from it. Rerun this after any schema change.
//
// Source: Prisma's own full-schema DDL (`migrate diff --from-empty`), rewritten
// so every statement is additive and safe to run on a database in any state:
//   enums      created if missing, and any missing values added
//   tables     CREATE TABLE IF NOT EXISTS, then every column ADD COLUMN IF NOT
//              EXISTS (a NOT NULL column that cannot be added to a table with
//              rows falls back to nullable, with a notice)
//   indexes    IF NOT EXISTS (a unique index blocked by duplicate rows is
//              reported, not fatal)
//   foreign keys  added if missing; a failure is reported, not fatal
// Nothing is dropped, altered or rewritten. Safe to run twice.

import { execSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'

const ddl = execSync('npx --no-install prisma migrate diff --from-empty --to-schema-datamodel prisma/schema.prisma --script', {
  encoding: 'utf8',
  stdio: ['ignore', 'pipe', 'ignore'],
})

// Split into statements, dropping comments.
const statements = ddl
  .split('\n')
  .filter((l) => !l.trim().startsWith('--'))
  .join('\n')
  .split(/;\s*\n/)
  .map((s) => s.trim())
  .filter(Boolean)

const q = (s) => s.replace(/'/g, "''")
const guard = (sql, what) =>
  `DO $$ BEGIN\n  ${sql};\nEXCEPTION WHEN duplicate_object OR duplicate_table THEN NULL;\n  WHEN others THEN RAISE NOTICE 'skipped ${q(what)}: %', SQLERRM;\nEND $$;`

const enums = []
const tables = []
const indexes = []
const fks = []

for (const s of statements) {
  let m
  if ((m = /^CREATE TYPE "([^"]+)" AS ENUM \((.*)\)$/s.exec(s))) {
    const [, name, values] = m
    const vals = values.split(',').map((v) => v.trim())
    enums.push(guard(`CREATE TYPE "${name}" AS ENUM (${vals.join(', ')})`, `enum ${name}`))
    for (const v of vals) enums.push(`ALTER TYPE "${name}" ADD VALUE IF NOT EXISTS ${v};`)
  } else if ((m = /^CREATE TABLE "([^"]+)" \((.*)\)$/s.exec(s))) {
    const [, name, body] = m
    const lines = body.split('\n').map((l) => l.trim().replace(/,$/, '')).filter(Boolean)
    const cols = lines.filter((l) => l.startsWith('"'))
    const out = [`CREATE TABLE IF NOT EXISTS "${name}" (\n  ${lines.join(',\n  ')}\n);`]
    for (const col of cols) {
      const colName = /^"([^"]+)"/.exec(col)[1]
      const nullable = col.replace(/\s+NOT NULL/, '')
      out.push(
        `DO $$ BEGIN\n  ALTER TABLE "${name}" ADD COLUMN IF NOT EXISTS ${col};\n` +
          `EXCEPTION WHEN others THEN\n  BEGIN\n    ALTER TABLE "${name}" ADD COLUMN IF NOT EXISTS ${nullable};\n` +
          `    RAISE NOTICE 'added ${q(name)}.${q(colName)} as nullable: %', SQLERRM;\n` +
          `  EXCEPTION WHEN others THEN RAISE NOTICE 'skipped ${q(name)}.${q(colName)}: %', SQLERRM;\n  END;\nEND $$;`,
      )
    }
    tables.push(out.join('\n'))
  } else if ((m = /^CREATE (UNIQUE )?INDEX "([^"]+)" (ON .*)$/s.exec(s))) {
    const [, unique = '', name, rest] = m
    indexes.push(guard(`CREATE ${unique}INDEX IF NOT EXISTS "${name}" ${rest}`, `index ${name}`))
  } else if ((m = /^ALTER TABLE "([^"]+)" ADD CONSTRAINT "([^"]+)" FOREIGN KEY/s.exec(s))) {
    fks.push(guard(s, `foreign key ${m[2]}`))
  } else if (/^CREATE SCHEMA/.test(s)) {
    // public always exists
  } else {
    throw new Error(`generate-sync-schema: unhandled statement:\n${s}`)
  }
}

const header = `-- ─────────────────────────────────────────────────────────────────────────────
-- getCalmly · Make this database match the app
-- ─────────────────────────────────────────────────────────────────────────────
-- Run this in the Supabase SQL Editor (works from a phone browser):
--   Supabase → your project → SQL Editor → New query → paste → Run
--
-- WHY THIS EXISTS
-- ---------------
-- Deploy-time migrations are best effort, and a few tables and columns were
-- only ever created by self-heal code. A database that falls behind the app
-- fails quietly: admin lists show empty and detail pages 404, because reads
-- fail soft. This script declares every enum, table, column, index and foreign
-- key the app expects, each one guarded, and adds whatever is absent.
--
-- SAFETY
-- ------
-- Purely additive. Nothing is dropped, truncated, altered or rewritten, and no
-- row is changed. Anything that cannot be added is reported as a NOTICE and
-- skipped instead of stopping the script. Safe to run twice, or on a database
-- that is already complete: it then does nothing.
--
-- GENERATED by scripts/generate-sync-schema.mjs from prisma/schema.prisma.
-- Do not edit by hand; run \`npm run db:sync-sql\` after changing the schema.
-- ─────────────────────────────────────────────────────────────────────────────
`

const sql = [
  header,
  '-- ── Enum types ───────────────────────────────────────────────────────────────\n',
  enums.join('\n'),
  '\n-- ── Tables and columns ───────────────────────────────────────────────────────\n',
  tables.join('\n\n'),
  '\n-- ── Indexes ─────────────────────────────────────────────────────────────────\n',
  indexes.join('\n'),
  '\n-- ── Foreign keys ────────────────────────────────────────────────────────────\n',
  fks.join('\n'),
  '',
].join('\n')

writeFileSync('prisma/sync_schema.sql', sql)
console.log(`prisma/sync_schema.sql: ${enums.length} enum statements, ${tables.length} tables, ${indexes.length} indexes, ${fks.length} foreign keys`)
